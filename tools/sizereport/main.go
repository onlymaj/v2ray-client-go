// Command sizereport builds the binary once per build-tag set and prints a
// markdown size breakdown: stripped and UPX size per tag set, and the
// biggest packages of the full build by symbol size (go tool nm -size).
//
// Usage (from the repo root):
//
//	go run ./tools/sizereport                 # print the report
//	go run ./tools/sizereport -write          # also replace it in README.md
//	go run ./tools/sizereport -pkg ./probe    # report another main package
//
// Symbol sizes come from an unstripped build (no -s -w), so they add up to
// less than the file size (headers, pclntab and DWARF are not symbols) and
// are not comparable to the stripped size; they only rank packages.
package main

import (
	"bufio"
	"bytes"
	"flag"
	"fmt"
	"log"
	"os"
	"os/exec"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
)

const (
	module      = "github.com/onlymaj/v2ray-client-go/"
	startMarker = "<!-- sizereport:start -->"
	endMarker   = "<!-- sizereport:end -->"
)

func main() {
	pkg := flag.String("pkg", "./cmd/v2ray-client-go", "main package to build")
	tagList := flag.String("tags", "vless vmess reality ws grpc", "optional build tags")
	upx := flag.String("upx", ".tools/upx", "upx binary (skipped when missing)")
	top := flag.Int("top", 15, "number of packages to list")
	write := flag.Bool("write", false, "replace the marked section of -readme")
	readme := flag.String("readme", "README.md", "file updated by -write")
	flag.Parse()
	log.SetFlags(0)

	tags := strings.Fields(*tagList)
	sets := [][]string{nil}
	for _, t := range tags {
		sets = append(sets, []string{t})
	}
	if len(tags) > 1 {
		sets = append(sets, tags)
	}
	if _, err := os.Stat(*upx); err != nil {
		*upx = ""
	}

	tmp, err := os.MkdirTemp("", "sizereport")
	if err != nil {
		log.Fatal(err)
	}
	defer os.RemoveAll(tmp)

	var out bytes.Buffer
	fmt.Fprintf(&out, "Generated by `go run ./tools/sizereport` for `%s` (linux/arm64, `-trimpath -ldflags=\"-s -w -buildid=\"`", *pkg)
	if *upx != "" {
		out.WriteString(", UPX `--best --lzma`")
	}
	out.WriteString(").\n\n| Tags | Stripped | UPX |\n|---|---:|---:|\n")
	for i, set := range sets {
		bin := filepath.Join(tmp, fmt.Sprintf("bin%d", i))
		if err := build(*pkg, set, true, bin); err != nil {
			log.Fatal(err)
		}
		name := strings.Join(set, " ")
		if name == "" {
			name = "(none)"
		}
		upxSize := "n/a"
		if *upx != "" {
			packed := bin + ".upx"
			cmd := exec.Command(*upx, "-q", "--best", "--lzma", "-o", packed, bin)
			if b, err := cmd.CombinedOutput(); err != nil {
				log.Fatalf("upx: %v\n%s", err, b)
			}
			upxSize = human(fileSize(packed))
		}
		fmt.Fprintf(&out, "| `%s` | %s | %s |\n", name, human(fileSize(bin)), upxSize)
		log.Printf("built %s", name)
	}

	full := sets[len(sets)-1]
	bin := filepath.Join(tmp, "full-syms")
	if err := build(*pkg, full, false, bin); err != nil {
		log.Fatal(err)
	}
	pkgs, groups, total, err := symbolSizes(bin)
	if err != nil {
		log.Fatal(err)
	}
	fmt.Fprintf(&out, "\nTop %d packages, all tags (symbol sizes from an unstripped build, %s of symbols in total):\n\n", *top, human(total))
	table(&out, "Package", pkgs, total, *top)
	out.WriteString("\nBy group:\n\n")
	table(&out, "Group", groups, total, 0)

	report := out.String()
	fmt.Print(report)
	if *write {
		if err := replaceSection(*readme, report); err != nil {
			log.Fatal(err)
		}
		log.Printf("updated %s", *readme)
	}
}

// build compiles pkg for linux/arm64 with the release flags; strip=false
// drops -s -w so go tool nm sees the symbol table.
func build(pkg string, tags []string, strip bool, out string) error {
	ldflags := "-buildid="
	if strip {
		ldflags = "-s -w -buildid="
	}
	cmd := exec.Command("go", "build", "-trimpath", "-ldflags="+ldflags,
		"-tags", strings.Join(tags, " "), "-o", out, pkg)
	cmd.Env = append(os.Environ(), "CGO_ENABLED=0", "GOOS=linux", "GOARCH=arm64")
	if b, err := cmd.CombinedOutput(); err != nil {
		return fmt.Errorf("go build %s (tags %q): %v\n%s", pkg, tags, err, b)
	}
	return nil
}

// symbolSizes sums symbol sizes per package and per group. BSS and
// undefined symbols are skipped since they take no space in the file.
func symbolSizes(bin string) (pkgs, groups map[string]int64, total int64, err error) {
	b, err := exec.Command("go", "tool", "nm", "-size", "-sort", "size", bin).Output()
	if err != nil {
		return nil, nil, 0, fmt.Errorf("go tool nm: %v", err)
	}
	pkgs, groups = map[string]int64{}, map[string]int64{}
	sc := bufio.NewScanner(bytes.NewReader(b))
	sc.Buffer(make([]byte, 1<<20), 1<<20)
	for sc.Scan() {
		// "  addr size type name", name may contain spaces.
		f := strings.Fields(sc.Text())
		if len(f) < 4 {
			continue
		}
		size, err := strconv.ParseInt(f[1], 10, 64)
		if err != nil || size == 0 {
			continue
		}
		switch f[2] {
		case "B", "b", "U":
			continue
		}
		p := pkgOf(strings.Join(f[3:], " "))
		pkgs[p] += size
		groups[groupOf(p)] += size
		total += size
	}
	return pkgs, groups, total, sc.Err()
}

// pkgOf extracts the import path from a symbol name such as
// "github.com/a/b.(*T).M", "crypto/tls.init" or "type:*net.Conn".
func pkgOf(sym string) string {
	switch {
	case strings.HasPrefix(sym, "type:"), strings.HasPrefix(sym, "go:itab."):
		return "(type metadata)"
	case strings.HasPrefix(sym, "go:"), strings.HasPrefix(sym, "$"):
		return "(runtime data)"
	}
	if i := strings.IndexByte(sym, '['); i >= 0 {
		sym = sym[:i] // generic instantiation arguments
	}
	slash := strings.LastIndexByte(sym, '/')
	dot := strings.IndexByte(sym[slash+1:], '.')
	if dot < 0 {
		return "(other)"
	}
	p := sym[:slash+1+dot]
	if strings.HasPrefix(p, module) {
		return "./" + p[len(module):]
	}
	return p
}

// groupOf folds a package path into a coarse bucket: our packages
// (./internal/...), a third-party module, or a std area.
func groupOf(p string) string {
	if strings.HasPrefix(p, "(") {
		return p
	}
	if p == "main" {
		return "(main package)"
	}
	parts := strings.Split(p, "/")
	switch {
	case parts[0] == ".":
		return p
	case strings.Contains(parts[0], "."): // third-party module
		if len(parts) > 3 {
			parts = parts[:3]
		}
		return strings.Join(parts, "/")
	case parts[0] == "vendor":
		return "std: vendor/golang.org/x/*"
	case parts[0] == "runtime", len(parts) > 1 && parts[0] == "internal" && parts[1] == "runtime":
		return "std: runtime"
	case parts[0] == "crypto", parts[0] == "net", parts[0] == "internal", parts[0] == "encoding":
		return "std: " + parts[0] + "/*"
	}
	return "std: other"
}

func table(out *bytes.Buffer, title string, m map[string]int64, total int64, limit int) {
	type kv struct {
		k string
		v int64
	}
	var rows []kv
	for k, v := range m {
		rows = append(rows, kv{k, v})
	}
	sort.Slice(rows, func(i, j int) bool {
		if rows[i].v != rows[j].v {
			return rows[i].v > rows[j].v
		}
		return rows[i].k < rows[j].k
	})
	if limit > 0 && len(rows) > limit {
		rows = rows[:limit]
	}
	fmt.Fprintf(out, "| %s | Size | Share |\n|---|---:|---:|\n", title)
	for _, r := range rows {
		fmt.Fprintf(out, "| `%s` | %s | %.1f%% |\n", r.k, human(r.v), 100*float64(r.v)/float64(total))
	}
}

func replaceSection(path, body string) error {
	b, err := os.ReadFile(path)
	if err != nil {
		return err
	}
	s := string(b)
	i := strings.Index(s, startMarker)
	j := strings.Index(s, endMarker)
	if i < 0 || j < i {
		return fmt.Errorf("%s: markers %s / %s not found", path, startMarker, endMarker)
	}
	s = s[:i+len(startMarker)] + "\n" + body + s[j:]
	return os.WriteFile(path, []byte(s), 0o644)
}

func fileSize(p string) int64 {
	st, err := os.Stat(p)
	if err != nil {
		log.Fatal(err)
	}
	return st.Size()
}

func human(n int64) string {
	switch {
	case n >= 1<<20:
		return fmt.Sprintf("%.2f MiB", float64(n)/(1<<20))
	case n >= 1<<10:
		return fmt.Sprintf("%.1f KiB", float64(n)/(1<<10))
	}
	return fmt.Sprintf("%d B", n)
}
